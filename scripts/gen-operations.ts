/**
 * Builds src/shared/operations.gen.ts from spec/openapi.yaml: every operation the
 * panel's manual console can call, with resolved request schemas. Default-probe
 * duplicates (/api/probe/... without {probeId}) are skipped when a probe-scoped twin exists.
 */
import { readFileSync, writeFileSync } from "node:fs";
import yaml from "js-yaml";
import { classify, type JsonSchema, type Operation, type OpParam } from "../src/shared/operations.ts";

const spec = yaml.load(readFileSync("spec/openapi.yaml", "utf8")) as Record<string, any>;

function pointer(ref: string): any {
  if (!ref.startsWith("#/")) throw new Error(`external ref ${ref}`);
  return ref.slice(2).split("/").reduce((o, k) => o?.[k.replace(/~1/g, "/").replace(/~0/g, "~")], spec);
}

function deref(x: any, depth = 0): any {
  if (depth > 10 || x === null || typeof x !== "object") return x;
  if (Array.isArray(x)) return x.map((v) => deref(v, depth + 1));
  if (x.$ref) return deref({ ...pointer(x.$ref), ...Object.fromEntries(Object.entries(x).filter(([k]) => k !== "$ref")) }, depth + 1);
  if (x.allOf) {
    const parts = x.allOf.map((p: any) => deref(p, depth + 1));
    const merged: any = { ...Object.fromEntries(Object.entries(x).filter(([k]) => k !== "allOf")) };
    for (const p of parts) {
      merged.type ??= p.type;
      merged.enum ??= p.enum;
      merged.description ??= p.description;
      merged.properties = { ...(merged.properties ?? {}), ...(p.properties ?? {}) };
      merged.required = [...(merged.required ?? []), ...(p.required ?? [])];
    }
    if (!Object.keys(merged.properties).length) delete merged.properties;
    if (!merged.required.length) delete merged.required;
    return deref(merged, depth + 1);
  }
  return Object.fromEntries(Object.entries(x).map(([k, v]) => [k, deref(v, depth + 1)]));
}

const paths = spec.paths as Record<string, any>;
const scopedTwins = new Set(Object.keys(paths).filter((p) => p.startsWith("/api/probe/{probeId}")).map((p) => p.replace("/api/probe/{probeId}", "/api/probe")));
const ops: Operation[] = [];
for (const [path, item] of Object.entries(paths)) {
  if (path === "/api/probe" || (path.startsWith("/api/probe/") && !path.includes("{probeId}") && scopedTwins.has(path))) continue;
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    if (!op) continue;
    const M = method.toUpperCase() as Operation["method"];
    const id = `${M} ${path}`;
    const rawParams = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p: any) => deref(p));
    const seen = new Set<string>();
    const params: OpParam[] = [];
    for (const p of rawParams) {
      if (!p || (p.in !== "path" && p.in !== "query") || seen.has(`${p.in}:${p.name}`)) continue;
      seen.add(`${p.in}:${p.name}`);
      params.push({ name: p.name, in: p.in, required: !!p.required, description: p.description, schema: (p.schema ?? {}) as JsonSchema });
    }
    const rb = op.requestBody ? deref(op.requestBody) : null;
    const media = rb?.content?.["application/json"];
    ops.push({
      id, method: M, path, summary: op.summary ?? "", description: (op.description ?? "").trim(), tags: op.tags ?? [],
      deprecated: !!op.deprecated, params, body: media?.schema ?? null, bodyExample: media?.example ?? null, ...classify(id, M),
    });
  }
}
ops.sort((a, b) => (a.tags[0] ?? "").localeCompare(b.tags[0] ?? "") || a.path.localeCompare(b.path));
writeFileSync(
  "src/shared/operations.gen.ts",
  `// Generated by scripts/gen-operations.ts from spec/openapi.yaml. Do not edit.\nimport type { Operation } from "./operations.js";\n\nexport const SPEC_VERSION = ${JSON.stringify(String(spec.info?.version ?? ""))};\nexport const OPERATIONS: Operation[] = ${JSON.stringify(ops, null, 1)};\n`,
);
console.log(`${ops.length} operations written`);
